/// The names every file has without declaring them: the standard library's
/// prelude and its own crates, the primitive types, and the attributes,
/// derives and macros the compiler and the standard library bring -- none of
/// them a dependency's, so none is put down to a glob.
pub struct StdNames;

impl StdNames {
    pub fn attribute(&self, name: &str) -> bool {
        ATTRIBUTES.contains(&name)
    }

    pub fn derive(&self, name: &str) -> bool {
        DERIVES.contains(&name)
    }

    pub fn macro_name(&self, name: &str) -> bool {
        MACROS.contains(&name)
    }

    pub fn prelude(&self, name: &str) -> bool {
        PRELUDE.contains(&name)
    }
}
